import re
from typing import List, Dict, Optional
from app.schemas.ai import (
    AiSummarizeRequest,
    AiSummaryResponse,
    AiGenerateFlashcardsRequest,
    AiFlashcardSchema,
    AiFlashcardsResponse,
    AiGenerateQuizRequest,
    AiQuizQuestionSchema,
    AiQuizResponse,
    AiExplainFormulaRequest,
    AiExplainFormulaResponse,
    AiChatRequest,
    AiChatResponse,
    AiStudyStatusResponse,
)


class AiStudyService:
    """Provider-independent educational AI study assistant engine for Naik Notes."""

    def __init__(self, provider: str = "internal"):
        self.provider = provider

    def get_status(self) -> AiStudyStatusResponse:
        return AiStudyStatusResponse(
            status="active",
            provider=f"NaikNotes-AI-StudyEngine ({self.provider})",
            version="1.0.0",
        )

    def summarize(self, request: AiSummarizeRequest) -> AiSummaryResponse:
        raw = request.context_text.strip()
        if not raw:
            return AiSummaryResponse(
                notebook_id=request.notebook_id,
                title="Empty Notes Summary",
                summary_markdown="*No note text or handwritten content found to summarize. Start writing or importing notes to generate a study summary.*",
                key_concepts=[],
                study_recommendations=["Write notes or import a PDF to generate summaries."],
            )

        # Extract sentences and keywords
        sentences = [s.strip() for s in re.split(r"[.\n]+", raw) if len(s.strip()) > 8]
        top_sentences = sentences[:5]

        # Extract potential concepts (capitalized words or prominent tokens)
        words = re.findall(r"\b[A-Z][a-zA-Z]{3,}\b", raw)
        unique_concepts = list(dict.fromkeys(words))[:6]
        if not unique_concepts:
            unique_concepts = ["Key Equations", "Definitions", "Core Principles"]

        summary_body = "### Lecture & Reading Overview\n\n"
        summary_body += f"This notebook covers **{len(sentences)} key topics** extracted from your handwritten notes and annotations.\n\n"
        summary_body += "**Core Highlights:**\n"
        for s in top_sentences:
            summary_body += f"- {s}.\n"

        summary_body += "\n---\n*Generated by Naik Notes AI Study Assistant.*"

        recommendations = [
            f"Review the derivations for {unique_concepts[0]}." if unique_concepts else "Review core concepts.",
            "Practice applying the primary formulas to sample problems.",
            "Self-test using the generated flashcard deck.",
        ]

        return AiSummaryResponse(
            notebook_id=request.notebook_id,
            title="Lecture & Study Summary",
            summary_markdown=summary_body,
            key_concepts=unique_concepts,
            study_recommendations=recommendations,
        )

    def generate_flashcards(
        self, request: AiGenerateFlashcardsRequest
    ) -> AiFlashcardsResponse:
        raw = request.context_text.strip()
        count = max(1, min(request.count, 15))

        # Default pedagogical flashcard templates if context is brief
        default_pairs = [
            ("What is the fundamental theorem or principle outlined in these notes?", "The principle establishes the core relationship between the input variables and observed system dynamics.", "Consider the foundational law stated in the introduction.", "medium"),
            ("How do you calculate or derive the primary formula in this topic?", "By taking the limit or integral over the domain with respect to the continuous parameters.", "Recall the boundary conditions.", "hard"),
            ("What are the primary assumptions of the model?", "Linearity, conservation of energy/momentum, and time-invariance.", "Think about system constraints.", "easy"),
            ("What does the primary derivative term represent physically?", "The rate of change or flux of the quantity per unit time or area.", "Units give a clue to the rate.", "medium"),
            ("Why is this concept significant in practical applications?", "It enables predictable optimization, error reduction, and system stability in real-world scenarios.", "Focus on real-world engineering outcomes.", "easy"),
        ]

        cards: List[AiFlashcardSchema] = []
        for i in range(count):
            q, a, h, diff = default_pairs[i % len(default_pairs)]
            if raw and len(raw) > 20:
                words = re.findall(r"\b[A-Z][a-z]+\b", raw)
                concept = words[i % len(words)] if words else "the core topic"
                q = f"In the context of {concept}: {q.lower()}"

            cards.append(
                AiFlashcardSchema(
                    id=f"card-{request.notebook_id}-{i + 1}",
                    question=q,
                    answer=a,
                    hint=h,
                    difficulty=diff,
                )
            )

        return AiFlashcardsResponse(
            notebook_id=request.notebook_id,
            flashcards=cards,
        )

